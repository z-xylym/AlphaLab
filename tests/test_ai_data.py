class FakeClient:
    calls=0
    def __init__(self,**kwargs):pass
    def __enter__(self):return self
    def __exit__(self,*args):pass
    def post(self,url,**kwargs):
        FakeClient.calls+=1
        assert 'Bearer test-not-real-key'==kwargs['headers']['Authorization']
        assert kwargs['json']['max_tokens']==2200
        return httpx.Response(200,request=httpx.Request('POST',url),json={
            'choices':[{'message':{'content':'已核实事实：测试夹具。分析推断：无。风险：不确定。'}}],
            'usage':{'prompt_tokens':100,'completion_tokens':20}})

@pytest.fixture
def fake():
    FakeClient.calls=0
    return FakeClient

def test_missing_key_timeout_and_dedup(system,fake):
    s,_,a,b=system
    with pytest.raises(SetupRequired):AI(b,replace(s,deepseek_api_key='')).generate('chat','q',{})
    service=AI(b,s,fake)
    first,cached=service.generate('stock','q',{'date':'2026-01-01'})
    assert not cached
    # New memories generated by the first response must not break idempotency.
    b.put('user_memories','new',{'q':'q'})
    second,cached=service.generate('stock','q',{'date':'2026-01-01'})
    assert cached and first==second and fake.calls==1
    class TimeoutClient(FakeClient):
        def post(self,*args,**kwargs):raise httpx.ReadTimeout('synthetic timeout')
    with pytest.raises(UserError):AI(b,s,TimeoutClient).generate('chat','timeout',{})
    with b.db.connect() as c:
        assert c.scalar(select(usage.c.status).where(usage.c.status=='unknown'))=='unknown'

def test_concurrent_quota_reservation(system,fake):
    s,auth,a,b=system
    user=auth.current(b.token);a.admin_update(user['id'],True,1)
    service=AI(b,s,fake)
    def run(n):
        try:service.generate('chat',str(n),{});return True
        except UserError:return False
    with ThreadPoolExecutor(max_workers=2) as pool:results=list(pool.map(run,[1,2]))
    assert sum(results)==1 and fake.calls==1

def test_budget_blocks_and_actual_cost(system,fake):
    s,_,a,b=system
    with pytest.raises(UserError):AI(b,replace(s,daily_budget=Decimal('0')),fake).generate('chat','q',{})
    AI(b,s,fake).generate('chat','q',{})
    with b.db.connect() as c:
        row=c.execute(select(usage)).mappings().one()
        assert row['input_tokens']==100
        assert row['cost']==Decimal('0.00026000')

def test_cache_refresh_failure_does_not_clear_data(system):
    _,auth,_,_=system
    data=MarketData(auth.db);calls=[]
    def load():calls.append(1);return {'items':[{'code':'600001','price':3}]}
    first=data.cached('test',100,'test-fixture',load)
    assert not first['stale']
    assert data.cached('test',100,'test-fixture',load)['items']==first['items']
    assert len(calls)==1
    with auth.db.begin() as c:c.execute(update(cache).where(cache.c.key=='test').values(expires_at=now()-timedelta(seconds=1)))
    def fail():raise ConnectionError('fixture')
    fallback=data.cached('test',100,'test-fixture',fail)
    assert fallback['stale'] and fallback['fetched_at']==first['fetched_at']
    with pytest.raises(DataUnavailable):data.cached('missing',10,'fixture',fail)

