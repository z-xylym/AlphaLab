def test_provider_preserves_leading_zero_codes(monkeypatch):
    import pandas as pd
    from types import SimpleNamespace
    from alphalab import provider
    payload=pd.DataFrame([{'代码':'000001','名称':'测试夹具','最新价':10}]).to_json(orient='split',force_ascii=False)
    monkeypatch.setattr(provider.subprocess,'run',lambda *a,**k:SimpleNamespace(stdout=payload))
    assert provider.call('stock_zh_a_spot_em').iloc[0]['代码']=='000001'

def test_official_policy_html_and_full_text(system,monkeypatch):
    _,auth,_,_=system
    original=httpx.Client
    def respond(request):
        if '/zhengce/zuixin/' in str(request.url):
            html='<ul><li><a href="/zhengce/content/20260101/a.htm">测试政策征求意见稿（测试夹具）</a><span>2026-01-01</span></li><li><a href="https://attacker.example/a">不可信测试链接标题</a>2026-01-01</li></ul>'
